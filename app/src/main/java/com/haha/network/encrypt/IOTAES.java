	public byte[] Cipher(byte input[])
	{
		int inLen=input.length;
		int bufLen=16*((int)Math.ceil((double)inLen/16));
		byte[] in = new byte[bufLen];
		System.arraycopy(input, 0, in, 0, inLen);
		int i;
		int length=bufLen;

		for (i = 0; i < length; i += 16)
		{
			Cipher(in,i);
		}
		return in;
	}

	public byte[] InvCipher(byte[] input)
	{
		byte in[] =input.clone();
		int i;
		int length=in.length;
		for (i = 0; i < length; i += 16)
		{
			InvCipher(in , i);
		}
		int len;
		for(len=in.length-1;len>0;len--){
			if(in[len]!=0)
				break;
		}
		byte result[]=new byte[len+1];
		System.arraycopy(in, 0, result,0,result.length);
		return result;
	}
	public void KeyExpansion(byte[] key, int w[][][])
	{
		int i, j, r, c;
		int rc[] = { 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36 };
		for (r = 0; r < 4; r++)
		{
			for (c = 0; c < 4; c++)
			{
				w[0][r][c] = key[r + c * 4]&0xff;
			}
		}

		for (i = 1; i <= 10; i++)
		{
			for (j = 0; j < 4; j++)
			{
				int t[]=new int[4];
				for (r = 0; r < 4; r++)
				{
					t[r] = ((j != 0)? w[i][r][j - 1] : w[i - 1][r][3])&0xff;

				}
				if (j == 0)
				{
					int temp = t[0];
					for (r = 0; r < 3; r++)
					{
						t[r] = Sbox[t[(r + 1) % 4]];
					}
					t[3] = Sbox[temp];
					t[0] ^= rc[i - 1];
					t[0]=t[0]&0xff;
				}
				for (r = 0; r < 4; r++)
				{
					w[i][r][j] = (w[i - 1][r][j] ^ t[r]);
					w[i][r][j]=w[i][r][j]&0xff;
				}
			}
		}
	}

	private int FFmul(int a, int b){
		byte bw[]=new byte[4];
		byte res = 0;
		int i;
		bw[0] = (byte)b;
		for (i = 1; i < 4; i++){
			bw[i] = (byte)(bw[i - 1] << 1);
			if ((bw[i - 1] & 0x80)!=0){
				bw[i] ^= 0x1b;
			}
		}
		for (i = 0; i < 4; i++){
			if (((a >> i) & 0x01)!=0){
				res ^= bw[i];
			}
		}
		return res;
	}

	private void Subints(int state[][]){
		int r, c;
		for (r = 0; r < 4; r++)
		{
			for (c = 0; c < 4; c++)
			{
				state[r][c] = Sbox[state[r][c]];
			}
		}
	}

	private void ShiftRows(int state[][]){
		int t[]=new int[4];
		int r, c;
		for (r = 1; r < 4; r++)
		{
			for (c = 0; c < 4; c++)
			{
				t[c] = state[r][(c + r) % 4];
			}
			for (c = 0; c < 4; c++)
			{
				state[r][c] = t[c];
			}
		}
	}

	private void MixColumns(int state[][])
	{
		int t[]=new int[4];
		int r, c;
		for (c = 0; c < 4; c++)
		{
			for (r = 0; r < 4; r++)
			{
				t[r] = state[r][c];
			}
			for (r = 0; r < 4; r++)
			{
				state[r][c] = (FFmul(0x02, t[r])
					^ FFmul(0x03, t[(r + 1) % 4])
					^ FFmul(0x01, t[(r + 2) % 4])
					^ FFmul(0x01, t[(r + 3) % 4]))&0xff;
			}
		}
	}

