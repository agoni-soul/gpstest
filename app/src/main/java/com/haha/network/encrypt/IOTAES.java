	private byte[] Cipher(byte[] input,int offset)
	{
		int state[][]=new int[4][4];
		int i, r, c;

		for (r = 0; r < 4; r++)
		{
			for (c = 0; c < 4; c++)
			{
				state[r][c] = input[offset+c * 4 + r]&0xff;
			}
		}

		log("Cipher.state1:",state);

		log("Cipher.w:",w[10]);
		AddRoundKey(state, w[0]);
		log("AddRoundKey.state:",state);
		for (i = 1; i <= 10; i++)
		{
			Subints(state);
			ShiftRows(state);
			if (i != 10)MixColumns(state);
			AddRoundKey(state, w[i]);
		}

		for (r = 0; r < 4; r++)
		{
			for (c = 0; c < 4; c++)
			{
				input[offset+c * 4 + r] = (byte)state[r][c];
			}
		}

		return input;
	}

